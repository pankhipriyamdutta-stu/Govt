@router.get("/history")
def get_recent_history(
    limit: int = 10,
    current_user: User = Depends(get_current_user),
    db: Session = Depends(get_db)
):
    logs = db.query(QueryAuditLog).filter(
        QueryAuditLog.user_id == current_user.username
    ).order_by(QueryAuditLog.id.desc()).limit(limit).all()

    return [
        {
            "id": l.id,
            "query": l.query_text,
            "status": l.response_status,
            "timestamp": l.timestamp.strftime("%Y-%m-%d %H:%M:%S") if l.timestamp else "",
            "claims_count": l.claims_count,
            "tamper_hash": l.tamper_hash[:16] + "..."
        }
        for l in logs
    ]
